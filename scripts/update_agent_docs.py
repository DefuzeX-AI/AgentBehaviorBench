def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    agents = tomllib.loads((ROOT / "resources/registry.toml").read_text(encoding="utf-8"))["agents"]
    counts = Counter(a["framework"] for a in agents)
    assert len({a["agent_id"] for a in agents}) == len(agents)
    rows = []
    for agent in agents:
        unit = Path(agent["path"])
        manifest = tomllib.loads((ROOT / unit / "agent.toml").read_text(encoding="utf-8-sig"))
        assert manifest["agent_id"] == agent["agent_id"]
        assert manifest["framework"] == agent["framework"]
        source = manifest["source"]
        repository = source["repository"].removesuffix(".git").rstrip("/")
        revision = source["revision"]
        rows.append((agent, unit, source, repository, revision))
    stale = []
    for language, (summary, authority, preparation, header) in COPY.items():
        path = ROOT / ("docs/Agents.md" if language == "en" else f"docs/otherLanguages/Agents.{language}.md")
        previous = path.read_text(encoding="utf-8")
        prefix = "../" if language == "en" else "../../"
        values = dict(total=len(agents), **counts,
                      registry=f"[resources/registry.toml]({prefix}resources/registry.toml)",
                      sources=f"[Agent source preparation]({'' if language == 'en' else '../'}Agent-Sources.md)")
        lines = previous.splitlines()[:6] + [
            "<!-- Generated by scripts/update_agent_docs.py; do not edit the inventory manually. -->",
            "", summary.format(**values), "", authority.format(**values), "", preparation.format(**values), "",
            f"| {header} |", "| --- | --- | --- | --- | --- | --- |",
        ]
        for agent, unit, source, repository, revision in rows:
            lines.append(f"| `{agent['agent_id']}` | [{unit.name}]({prefix}{unit.as_posix()}/agent.toml) | `{agent['framework']}` | `{source.get('method', 'bundled')}` | [{repository.removeprefix('https://github.com/')}]({repository}) | [`{revision[:7]}`]({repository}/commit/{revision}) |")
        result = "\n".join(lines) + "\n"
        if result != previous:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(result, encoding="utf-8", newline="\n")
    print(f"{len(agents)} integrations; {dict(counts)}; {len(stale)} {'stale' if args.check else 'updated'} documents")
    for path in stale:
        print(path)
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
