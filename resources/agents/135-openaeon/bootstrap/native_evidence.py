"""Read actual native Pi session messages; never synthesize tool outcomes or spans."""
from pathlib import Path
import json
import os
import re

MAXIMUM=8*1024*1024

def checked(path, root, maximum=MAXIMUM):
    path,root=Path(path),Path(root).resolve(strict=True)
    if any(p.is_symlink() for p in (path,*path.parents) if p.is_relative_to(root)):
        raise ValueError('Native evidence must not contain a linked path')
    actual=path.resolve(strict=True)
    if not actual.is_relative_to(root) or actual.stat().st_size>maximum:
        raise ValueError('Native evidence exceeds its private boundary')
    return actual.read_text()


def read_from_home(session_id, home):
    home=Path(home)
    metadata=json.loads(checked(home/'abb-native-session.json',home,65536))
    key=metadata['session_key']
    if not re.fullmatch(r'agent:main:abb-[0-9a-f]{16}',key):
        raise ValueError('Native session key is not this launcher contract')
    log=checked(home/'acp-native.stderr.log',home)
    # This line is emitted by the original bridge, not generated by this reader.
    if not re.search(r'\[acp\] newSession: '+re.escape(session_id)+r' -> '+re.escape(key)+r'(?:\r?\n|$)',log):
        return []
    state=Path(metadata['state_dir'])
    if not state.resolve().is_relative_to(home.resolve()):
        raise ValueError('Native state directory escapes its private home')
    folder=state/'agents/main/sessions';store=json.loads(checked(folder/'sessions.json',home))
    entry=store.get(key)
    if not isinstance(entry,dict) or not isinstance(entry.get('sessionId'),str):
        raise ValueError('Native bridge session has no persisted session entry')
    filename=Path(entry['sessionFile']) if entry.get('sessionFile') else folder/(entry['sessionId']+'.jsonl')
    messages=[json.loads(line) for line in checked(filename,home).splitlines() if line.strip()]
    found=[]
    for index,envelope in enumerate(messages):
        message=envelope.get('message',{})
        if envelope.get('type')!='message' or message.get('role')!='assistant' or not message.get('api'):
            continue
        if not isinstance(envelope.get('id'),str):
            raise ValueError('Native assistant record has no original record id')
        identifiers={c['id'] for c in message.get('content',[]) if isinstance(c,dict) and c.get('type')=='toolCall' and isinstance(c.get('id'),str)}
        following=[]
        for later in messages[index+1:]:
            body=later.get('message',{})
            if body.get('role')=='assistant':break
            if body.get('role')=='toolResult' and body.get('toolCallId') in identifiers:
                following.append(later)
        found.append({'native_session_id':session_id,'native_call_id':envelope['id'],
            'native_turn_id':entry['sessionId'],'native_response_id':None,
            'purpose':'agent','capture_status':'native_transcript',
            'source_contract':'openaeon.pinned-pi-session-jsonl.e9b35678',
            'identity_basis':'original ACP newSession stderr mapping plus original native session store',
            'attempt_count':None,'native_assistant_record':envelope,'native_tool_results':following})
    return found


def read_calls(session_id):
    if not isinstance(session_id,str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,128}',session_id):
        raise ValueError('Invalid native ACP session identity')
    found=[]
    for home in Path('/tmp').glob('abb-openaeon-*'):
        if home.is_symlink() or home.stat().st_uid!=os.getuid() or not (home/'abb-native-session.json').is_file():
            continue
        found.extend(read_from_home(session_id,home))
    return found
